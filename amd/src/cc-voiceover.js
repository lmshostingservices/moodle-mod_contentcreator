define([], function () {
    'use strict';

    /**
     * Language code → human-readable label map.
     *
     * Used by the language-switcher pill bar (cc-language-switcher.js) and by
     * any code that needs to display a readable name for a BCP-47 language tag.
     *
     * Single source of truth — previously duplicated inline inside
     * player5.js::renderTopicsGrid as a local `_langLabels` variable.
     */
    var LANGUAGE_LABELS = {
        'en-AU': 'English (Australia)',
        'en-GB': 'English (UK)',
        'en-US': 'English (US)',
        'en-IN': 'English (India)',
        'vi-VN': 'Vietnamese',
        'cmn-CN': 'Mandarin (Simplified)',
        'cmn-TW': 'Mandarin (Taiwan)',
        'yue-HK': 'Cantonese',
        'ar-XA': 'Arabic',
        'ko-KR': 'Korean',
        'ja-JP': 'Japanese',
        'hi-IN': 'Hindi',
        'pa-IN': 'Punjabi (India)',
        'fil-PH': 'Filipino',
        'es-US': 'Spanish',
        'es-ES': 'Spanish (Spain)',
        'pt-BR': 'Portuguese (Brazil)',
        'pt-PT': 'Portuguese (Portugal)',
        'id-ID': 'Indonesian',
        'th-TH': 'Thai',
        'fr-FR': 'French',
        'de-DE': 'German',
        'it-IT': 'Italian',
        'ru-RU': 'Russian',
        'nl-NL': 'Dutch',
        'pl-PL': 'Polish'
    };

    /**
     * Returns the effective TTS language code to use for a voiceover request.
     *
     * Uses the additional-language code when the student or teacher has switched
     * to an additional language tab, falling back to the activity's primary voice
     * language.  This is the single correct answer to "which language do I send
     * to the TTS API right now?" — replacing the scattered `(activeLang || voiceLanguage)`
     * expressions that existed at five separate formData.append call-sites in
     * player5.js.
     *
     * @param {string|null} activeLang    The currently-active additional language
     *                                    code (e.g. 'vi-VN'), or null/empty when
     *                                    the primary language is active.
     * @param {string}      voiceLanguage The primary voice language from
     *                                    manifest.voiceSettings.language.
     * @returns {string} BCP-47 language code to send to the TTS API.
     */
    var getEffectiveLang = function (activeLang, voiceLanguage) {
        return (activeLang && activeLang.length > 0) ? activeLang : (voiceLanguage || 'en-AU');
    };

    /**
     * Returns true when a single manifest section's voiceover is ready for playback.
     *
     * A section is considered complete when ANY of the following is true:
     *   - slideType === 'activity' — activity slides never have voiceover.
     *   - voiceoverUrl === 'pregenerated' — audio was generated by the teacher and
     *     persisted to the Moodle file store; the player fetches it on demand.
     *   - voiceoverStatus === 'complete' AND voiceoverUrl is an HTTPS URL — the
     *     standard case after a successful TTS generation.
     *
     * Previously defined as the inner function `allVoiceoversComplete` inside
     * preloadVoiceovers() in player5.js.
     *
     * @param {Object} section  A manifest section object.
     * @returns {boolean}
     */
    var isSectionVoiceoverComplete = function (section) {
        return section.slideType === 'activity' ||
            section.voiceoverUrl === 'pregenerated' ||
            (section.voiceoverStatus === 'complete' &&
             typeof section.voiceoverUrl === 'string' &&
             section.voiceoverUrl.startsWith('http'));
    };

    /**
     * Returns true when every section in the array has a ready voiceover.
     *
     * @param {Array} sections  Array of manifest section objects.
     * @returns {boolean}
     */
    var allVoiceoversComplete = function (sections) {
        return sections.every(isSectionVoiceoverComplete);
    };

    return {
        LANGUAGE_LABELS:            LANGUAGE_LABELS,
        getEffectiveLang:           getEffectiveLang,
        isSectionVoiceoverComplete: isSectionVoiceoverComplete,
        allVoiceoversComplete:      allVoiceoversComplete
    };
});
